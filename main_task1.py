# time: Робить симуляцію реалістичною та видимою.
# uuid: Робить кожну заявку унікальною та відстежуваною.

import queue
import time
import uuid

# Створити чергу заявок
request_queue = queue.Queue()

def generate_request():
    """Створює нову унікальну заявку та додає її до черги."""
    # Унікальний ID заявки
    request_id = str(uuid.uuid4())
    print(f"Заявка {request_id[:8]}... Створена і додана до черги.")
    # Додати заявку до черги
    request_queue.put(request_id)
    
def process_request():
    """Видаляє заявку з черги та імітує її обробку."""
    try:
        # Видалити заявку з черги (FIFO)
        # Негайно повертає елемент. Якщо черга пуста, get_nowait не блокує програму, а натомість викидає виняток (queue.Empty).
        request_id = request_queue.get_nowait()
        # Імітація обробки
        print(f"Заявка {request_id[:8]}... Обробляється.")
        # Повідомляємо черзі, що елемент був успішно оброблений
        # task_done гарантує, що код готовий до багатопотокового режиму
        request_queue.task_done()
    except queue.Empty:
        # Якщо черга пуста
        print("Черга пуста. Очікування нових заявок.")

def main_loop(num_iterations=10):
    """Головний цикл програми, що імітує роботу сервісного центру."""
    print("--- Симуляція Сервісного Центру (Початок) ---")
    
    for i in range(num_iterations):
        # 1. Генерація нових заявок (імітуємо випадковий прихід)
        if i % 2 == 0:  # Створюємо заявку кожні 2 ітерації
            generate_request()
        
        # 2. Обробка заявок
        process_request()
        
        # Імітація часу на виконання роботи (затримка)
        time.sleep(0.5) 
    
    print("--- Симуляція Сервісного Центру (Кінець) ---")

# Запуск симуляції
main_loop()